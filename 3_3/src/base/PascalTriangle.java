package base;

public class PascalTriangle {

    public static void main(String[] args) {
        //1. Объявляем треугольник Паскаля
        int rows = 8;
        int[][] trianglePascal = buildPascalTriangle(rows);
        //2. Выводим треугольник
        printTriangle(trianglePascal);
        //3. Выводим сумму элементов и вторую степень каждой строки
        printSums(trianglePascal);
    }

    //1. Метод построения треугольника Паскаля
    private static int[][] buildPascalTriangle(int rows) {
        //8 строк, зубчатый массив
        int[][] trianglePascal = new int[rows][]; //создаем новый массив с 8 строками
        for (int i = 0; i < rows; i++) { //внешний цикл: строки, где i с 0, пока i<8, круг +1
            //первое и последнее число в строке = 1
            trianglePascal[i] = new int[i + 1]; //длина строки = размеру нового массива (значение строки +1)
            trianglePascal[i][0] = 1; //значение первого элемента строки и столбца равны 1
            trianglePascal[i][i] = 1; //значения последнего элемента строки и столбца равны 1
            //каждое число (кроме первого и последнего) в строке равно сумме двух чисел, стоящих над ним
            for (int j = 1; j < i; j++) { //внутренний цикл, где j c 1, пока j<i, круг +1
                trianglePascal[i][j] = trianglePascal[i - 1][j - 1] + trianglePascal[i - 1][j]; //значение элемента по [i][j]=сумме двух чисел, стоящих над значением элемента по [i][j]
            }
        }
        return trianglePascal;
    }
//trianglePascal=[00000000] [?]
//ВНЕШНИЙ цикл: i=0; 0<8;
//trianglePascal по строке [0]=длине массива в один элемент [0]; trianglePascal[0][0]=1; trianglePascal[0][0]=1;
//ВНУТРЕННИЙ цикл: j=1; 1<0-false, возвращаемся во ВНЕШНИЙ цикл; i=1;
//ВНЕШНИЙ цикл: i=1; 1<8;
//trianglePascal по строке [1]=длине массива в два элемента[0, 0]; trianglePascal[1][0]=1; trianglePascal[1][1]=1;
//ВНУТРЕННИЙ цикл: j=1; 1<1-false, возвращаемся во ВНЕШНИЙ цикл; i=2;
//ВНЕШНИЙ цикл: i=2; 2<8;
//trianglePascal по строке[2]=длине массива в три элемента[0,0,0]; trianglePascal[2][0]=1; trianglePascal[2][2]=1;
//ВНУТРЕННИЙ цикл: j=1; 1<2-true, проваливаемся во внутренний цикл:
//trianglePascal[2][1]=[1][0]+[1][1]=1+1=2; j=2
//ВНУТРЕННИЙ цикл: j=2; 2<2-false, возвращаемся во ВНЕШНИЙ цикл; i=3;
/*Итог: 1. Создали новый массив из 8 строк и неизвестным количеством столбцов
        2. Цикл с условием, что строим строки до 7 включительно
        3. Определили количество столбцов: каждый след ряд будет на один столбец больше
        4. Определили: первая левая колонка всегда 1, последняя правая колонка всегда 1
        5. Цикл с условием, где j c 1, чтоб не трогать первую колонку, j меньше i, чтоб не трогать последнюю колонку
        6. Указали, что все цифры (кроме первой и последней колонки) равны: цифра строкой выше и ячейкой левее + цифра строкой выше ровно над текущей [i][j]
 */

    //2. Метод вывода треугольника (с выравниванием по центру)
    public static void printTriangle(int[][] trianglePascal) {
        int rows = trianglePascal.length; //rows=8
        //Находим максимальную ширину для центровки всех строк, которые выше (последняя строка самая длинная)
        int maxWidth = 0; //начальное значение ширины последней строки
        for (int num : trianglePascal[rows - 1]) { //для всех num перебери все значения последней строки
            maxWidth += String.valueOf(num).length() + 1; //maxWidth=maxWidth+(valueOf-преврати в символ; length-посчитай количество символов; добавь 1 пробел после каждого числа, не цифры!)
        }
        for (int i = 0; i < rows; i++) { //цикл, где i c 0, i<8, круг +1
            //Определяем размер текущей строки с учетом пробелов между цифрами
            int currentWidth = 0; //начальное значение ширины текущей строки
            for (int num : trianglePascal[i]) { //для всех num перебери все значения всех строк
                currentWidth += String.valueOf(num).length() + 1; //currentWidth=currentWidth+(valueOf-преврати в символ; length-посчитай количество символов; добавь 1 пробел после каждого числа, не цифры!)
            }
            //Определяем количество отступов перед числами для центрирования таблицы
            int padding = (maxWidth - currentWidth) / 2; //отступы=максимальная ширина-ширина текущей строки/2
            for (int p = 0; p < padding; p++) { //цикл, где p c 0, пока p<padding, круг +1
                System.out.print(" "); //ставим пробел
            }
            //Печатаем числа с пробелом
            for (int j = 0; j < trianglePascal[i].length; j++) { //цикл, где j c 0, пока j<количеству столбцов, круг +1
                System.out.print(trianglePascal[i][j] + " "); //ставим значение соответствующее индексам + пробел
            }
            System.out.println(); //переносим строку
        }
    }
//1. rows=8; maxWidth=0; num:7; maxWidth=20
//2. i=0; 0<8; currentWidth=0; num по [0] это 1; currentWidth=2;
//2.1 padding=(20-2)/2=9; p=0; 0<9; " ";
//2.2 j=0; 0<1; вывели число по [i][j] с " ";
//Итог: 1. Размер нижней строки: 20 символов. 2 Размер текущей строки (1 круг): 2 символа 2.1 Размер отступов (1 круг): 9 пробелов 2.2 Вывод: число с 1 пробелом

    //3. Метод вывода суммы элементов каждой строки с проверкой, равна ли сумма 2 степени строки
    public static void printSums(int[][] trianglePascal) {
        System.out.println("Сумма элементов и вторая степень каждой строки:");
        for (int i = 0; i < trianglePascal.length; i++) { //цикл, где i=, i<8, круг +1
            int sum = 0; //начальное значение суммы элементов каждой строки
            for (int num : trianglePascal[i]) { //для всех num перебери все строки
                sum += num; //sum=sum+num
            }
            System.out.printf("Строка %d: сумма: %d; степень: 2^%d = %d; сумма и степень равны? %s%n", //форматированный вывод, где
                    i, sum, i, (int) Math.pow(2, i), //строка по [i]: sum; степень строки по [i]= результат вычислений 2 степени строки
                    sum == Math.pow(2, i) ? "ДА" : "НЕТ"); //тернарный оператор, если sum равна 2 степени строки по [i], то true-ДА
        }
    }
//i=0; 0<8; sum=0; num по первой строке [0] это 1; sum=0+1=1; i=1
//i=1; 1<8; sum=0; num по второй строке [1] это 1, 1; sum=0+1+1=2; i=2 и тд
}